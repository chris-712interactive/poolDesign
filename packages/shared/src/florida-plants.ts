/**
 * Florida pool-yard plants and trees as placeable catalog items.
 *
 * Visual / 3D only — not sold on the estimate. A company can add a custom
 * landscaping line if they need to bill plantings.
 *
 * This is a production-builder palette (species that actually get planted
 * around Florida pools), not every plant that can survive in the state.
 * Invasives that are illegal to sell (Brazilian pepper, Australian pine,
 * melaleuca, air potato) are omitted on purpose.
 */

