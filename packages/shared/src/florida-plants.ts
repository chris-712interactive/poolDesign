const BY_ID = new Map(FLORIDA_PLANTS.map((p) => [p.id, p]));

export function getFloridaPlant(
  id: string | undefined | null,
): FloridaPlant | undefined {
  if (!id) return undefined;
  return BY_ID.get(id);
}

export function isFloridaPlantId(id: string | undefined | null): boolean {
  return !!id && BY_ID.has(id);
}

export function isYardLandscapeStructureId(
  id: string | undefined | null,
): boolean {
  return (
    id === "planter" || id === "trellis" || id === "trellis_arbor"
  );
}

export function isLandscapingCatalogId(id: string | undefined | null): boolean {
  return isFloridaPlantId(id) || isYardLandscapeStructureId(id);
}

export function plantsInGroup(group: PlantGroup): FloridaPlant[] {
  return FLORIDA_PLANTS.filter((p) => p.group === group);
}

export function plantCssColor(c: PlantColor): string {
  return `rgb(${c.r}, ${c.g}, ${c.b})`;
}

export function plantDisplayName(plant: FloridaPlant): string {
  return plant.native ? `${plant.name} · native` : plant.name;
}

export function plantDescription(plant: FloridaPlant): string {
  const bits = [plant.botanical];
  if (plant.native) bits.push("Florida native");
  if (plant.description) bits.push(plant.description);
  return bits.join(" — ");
}
